/**
 * Build a build with cached artwork with real Wikimedia thumbnails.
 * Requires outbound HTTPS at build time only (not at viewing time).
 * Uses Commons Action API URLs, never guessed CDN paths or proxy services.
 *
 * Run: npm run cache:art
 * Optional: WIKIMEDIA_USER_AGENT='YourApp/1.0 (contact@domain.test)' npm run cache:art
 */
import fs from 'node:fs/promises';
import { FEATURED_IMAGE_FILENAMES, FEATURED_FILE_PAGES } from '../.cache/art/featured-images.js';
const output = new URL('../src/embedded-art.ts', import.meta.url);
const USER_AGENT =
  process.env.WIKIMEDIA_USER_AGENT || 'ATELIER-Living-Palette/0.6 (offline education preview)';
const MAX_IMAGE_BYTES = 2_000_000;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const media = Object.entries(FEATURED_IMAGE_FILENAMES);
const success = {};
const failures = [];
for (let i = 0; i < media.length; i++) {
  const [id, filename] = media[i];
  try {
    const search = new URL('https://commons.wikimedia.org/w/api.php');
    for (const [k, v] of Object.entries({
      action: 'query',
      titles: 'File:' + filename,
      prop: 'imageinfo',
      iiprop: 'url|mime',
      iiurlwidth: '500',
      format: 'json',
      origin: '*',
    }))
      search.searchParams.set(k, v);
    const resp = await fetch(search, {
      headers: { 'User-Agent': USER_AGENT, Accept: 'application/json' },
      signal: AbortSignal.timeout(20000),
    });
    if (!resp.ok) throw Error(`API HTTP ${resp.status}`);
    const json = await resp.json();
    const page = Object.values(json.query?.pages ?? {})[0];
    if (!page || page.missing) throw Error('Commons file not found');
    const info = page.imageinfo?.[0];
    const url = info?.thumburl || info?.url;
    if (!url) throw Error('No usable media URL');
    const image = await fetch(url, {
      headers: { 'User-Agent': USER_AGENT },
      signal: AbortSignal.timeout(30000),
    });
    if (!image.ok) throw Error(`Image HTTP ${image.status}`);
    const mime = (image.headers.get('content-type') || '').split(';')[0].toLowerCase();
    if (!['image/jpeg', 'image/png', 'image/webp', 'image/gif'].includes(mime))
      throw Error(`Not a supported image: ${mime}`);
    const bytes = Buffer.from(await image.arrayBuffer());
    if (!bytes.length || bytes.length > MAX_IMAGE_BYTES)
      throw Error(`Image size ${bytes.length} unsupported`);
    success[id] = `data:${mime};base64,${bytes.toString('base64')}`;
    console.log(`[${i + 1}/${media.length}] ✓ ${filename} · ${Math.round(bytes.length / 1024)} KB`);
  } catch (e) {
    failures.push({ id, filename, reason: e.message, source: FEATURED_FILE_PAGES[id] });
    console.warn(`[${i + 1}/${media.length}] ✗ ${filename} — ${e.message}`);
  }
  await sleep(200);
}
if (!Object.keys(success).length) {
  console.error(
    'No artwork images downloaded; preserving existing embedded-art.ts so the build is not damaged.',
  );
  process.exit(1);
}
const notice = `/** Generated by scripts/cache-featured.mjs. Includes actual Wikimedia media bytes.\n * Examine license and reuse permissions at the original file pages.\n * Do not commit generated bytes unless appropriate for your project.\n */\n`;
await fs.writeFile(
  output,
  notice +
    'export const EMBEDDED_ART_IMAGES: Readonly<Record<string,string>> = ' +
    JSON.stringify(success, null, 2) +
    ';\n',
);
await fs.writeFile(
  new URL('../assets-report.json', import.meta.url),
  JSON.stringify(
    { generatedAt: new Date().toISOString(), cached: Object.keys(success), failures },
    null,
    2,
  ),
);
console.log(
  `\nSaved ${Object.keys(success).length}/${media.length} artwork images for offline embedding.`,
);
